export const getServiceIcon = (iconName: string): LucideIcon => {
  if (ICON_MAP[iconName]) {
    return ICON_MAP[iconName];
  }
  // Default fallbacks
  return Sparkles;
};

export const renderServiceIcon = (iconName: string, className: string = 'w-5 h-5'): React.ReactElement => {
  const IconComponent = getServiceIcon(iconName);
  return <IconComponent className={className} />;
};
